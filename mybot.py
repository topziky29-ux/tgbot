# Обновленная функция рассылки расписания с учетом подгруппы и закрепления сообщений
async def send_daily_schedule(context: ContextTypes.DEFAULT_TYPE):
    tomorrow = datetime.now() + timedelta(days=1)
    weekday = get_russian_weekday(tomorrow)
    week_number, week_type = get_week_for_date(tomorrow)
    
    logger.info(f"🔄 Начинаю ежедневную рассылку расписания на {tomorrow.strftime('%d.%m.%Y')} ({weekday}) - {week_type} неделя №{week_number}")
    
    # Для каждой группы отправляем расписание только соответствующим пользователям и чатам
    for group_name in GROUPS:
        # Получаем пользователей этой группы
        users = get_users_by_group(group_name)
        
        # Получаем чаты этой группы
        chats = get_chats_by_group(group_name)
        
        # Рассылка пользователям с учетом их подгруппы
        for user_data in users:
            user_id = user_data[0]
            
            # 🟢 ПРАВИЛЬНОЕ получение подгруппы пользователя:
            subgroup = user_data[4] if len(user_data) > 4 and user_data[4] else "Обе подгруппы"
            
            filtered_schedule = get_filtered_schedule(group_name, weekday, week_type, week_number, subgroup)
            
            message = (
                f"📅 РАСПИСАНИЕ на завтра ({tomorrow.strftime('%d.%m.%Y')}, {weekday}) для группы {group_name}:\n"
                f"👥 Подгруппа: {subgroup}\n\n"
                f"{filtered_schedule}\n\n"
                f"({week_type} неделя, неделя №{week_number})"
            )
            
            try:
                await context.bot.send_message(chat_id=user_id, text=message)
                logger.info(f"✅ Отправлено расписание пользователю {user_id} (группа: {group_name}, подгруппа: {subgroup})")
            except Exception as e:
                logger.error(f"❌ Не удалось отправить расписание пользователю {user_id}: {e}")
        
        # Рассылка в чаты (для чатов используем "Обе подгруппы" по умолчанию) с закреплением
        for chat_data in chats:
            chat_id = chat_data[0]
            
            filtered_schedule = get_filtered_schedule(group_name, weekday, week_type, week_number, "Обе подгруппы")
            
            message = (
                f"📅 РАСПИСАНИЕ на завтра ({tomorrow.strftime('%d.%m.%Y')}, {weekday}) для группы {group_name}:\n\n"
                f"{filtered_schedule}\n\n"
                f"({week_type} неделя, неделя №{week_number})"
            )
            
            try:
                # Отправляем сообщение
                sent_message = await context.bot.send_message(chat_id=chat_id, text=message)
                
                # Открепляем старое сообщение и закрепляем новое
                await unpin_old_schedule(context, chat_id)
                await pin_new_schedule(context, chat_id, sent_message.message_id)
                
                logger.info(f"✅ Отправлено и закреплено расписание в чат {chat_id} (группа: {group_name})")
            except Exception as e:
                logger.error(f"❌ Не удалось отправить расписание в чат {chat_id}: {e}")
    
    logger.info("✅ Ежедневная рассылка расписания завершена")

# Функция для получения отфильтрованного расписания
def get_filtered_schedule(group_name, weekday, week_type, current_week, subgroup):
    """Получение расписания с фильтрацией по неделе и подгруппе"""
    if group_name in SCHEDULE and week_type in SCHEDULE[group_name] and weekday in SCHEDULE[group_name][week_type]:
        schedule_text = SCHEDULE[group_name][week_type][weekday]
        filtered_schedule = parse_schedule(schedule_text, current_week, subgroup)
        return filtered_schedule
    return "На этот день пар нет! 🎉"
    
