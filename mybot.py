def calculate_blackjack_score(hand):
    """Подсчет очков в блекджеке"""
    score = 0
    aces = 0
    
    for card in hand:
        if card in ['J', 'Q', 'K']:
            score += 10
        elif card == 'A':
            aces += 1
            score += 11
        else:
            score += int(card)
    
    # Корректируем тузы
    while score > 21 and aces > 0:
        score -= 10
        aces -= 1
    
    return score

